from __future__ import annotations
import argparse, json, random, re
from pathlib import Path
import numpy as np
import pandas as pd
import torch
from torch import nn
from torch.utils.data import Dataset, DataLoader

HORIZONS = 9

def set_seed(seed):
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available(): torch.cuda.manual_seed_all(seed)

def safe_name(value):
    return re.sub(r'[^A-Za-z0-9_.-]+','_',str(value))

class IndividualLSTM(nn.Module):
    def __init__(self, hidden=16, dropout=0.25):
        super().__init__()
        self.lstm = nn.LSTM(input_size=5, hidden_size=hidden, batch_first=True)
        self.head = nn.Sequential(nn.Linear(hidden, hidden), nn.ReLU(), nn.Dropout(dropout), nn.Linear(hidden,HORIZONS))
    def forward(self, x):
        z,_ = self.lstm(x)
        return self.head(z[:,-1,:])

class Windows(Dataset):
    def __init__(self, windows): self.windows=windows
    def __len__(self): return len(self.windows)
    def __getitem__(self, i):
        w=self.windows[i]
        return (torch.from_numpy(w['x']),torch.from_numpy(w['y']),torch.from_numpy(w['mask']))

def get_panel(path):
    df = pd.read_csv(path, parse_dates=['date'])
    needed={'date','crop_id','price_thb_kg'}
    if not needed.issubset(df.columns): raise ValueError(f'CSV must include {sorted(needed)}')
    if df.duplicated(['crop_id','date']).any(): raise ValueError('Duplicate crop/date records')
    df['date']=df['date'].dt.to_period('M').dt.to_timestamp()
    crops=sorted(df.crop_id.dropna().unique().tolist())
    panel={}
    for crop in crops:
        sub=df[df.crop_id==crop].set_index('date')['price_thb_kg'].sort_index()
        if (sub.dropna()<=0).any(): raise ValueError(f'{crop}: prices must be positive')
        dates=pd.date_range(sub.index.min(),sub.index.max(),freq='MS')
        panel[crop]=sub.reindex(dates).astype(float)
    return panel

def make_windows(ser, lookback, train_end, val_end):
    """Create origin-date split, with labels truncated to each split's end date."""
    dates=ser.index
    raw=ser.to_numpy(dtype=float)
    logs=np.full(len(raw),np.nan)
    valid=np.isfinite(raw)&(raw>0)
    logs[valid]=np.log(raw[valid])
    training=logs[(dates<=train_end)&np.isfinite(logs)]
    if len(training)<36: raise ValueError(f'Only {len(training)} observed train months; need at least 36')
    mu=float(np.mean(training)); sd=max(float(np.std(training)),0.05)
    seen=valid.astype('float32')
    filled=pd.Series(logs).ffill().to_numpy()
    gap=np.full(len(raw),24,dtype='float32'); last=-1
    for i in range(len(raw)):
        if valid[i]:last=i
        if last>=0:gap[i]=min(i-last,24)
    months=dates.month.to_numpy()
    normalized=np.clip((np.nan_to_num(filled,nan=mu)-mu)/sd,-8,8)
    features=np.column_stack([normalized,seen,gap/24,
        np.sin(2*np.pi*(months-1)/12),np.cos(2*np.pi*(months-1)/12)]).astype('float32')
    outputs={k:[] for k in ('train','val','test')}
    for i in range(lookback-1,len(raw)-1):
        if not np.isfinite(filled[i]):continue
        origin=dates[i]
        split='train' if origin<=train_end else ('val' if origin<=val_end else 'test')
        ceiling=train_end if split=='train' else (val_end if split=='val' else dates[-1])
        y=np.zeros(HORIZONS,dtype='float32'); mask=np.zeros(HORIZONS,dtype='float32')
        for h in range(1,HORIZONS+1):
            j=i+h
            if j<len(raw) and dates[j]<=ceiling and valid[j]:
                y[h-1]=(logs[j]-mu)/sd;mask[h-1]=1
        if mask.sum()==0:continue
        outputs[split].append({'x':features[i-lookback+1:i+1].copy(), 'y':y,'mask':mask,
                               'origin':origin,'last_price':float(np.exp(filled[i]))})
    return outputs,{'mean':mu,'sd':sd,'train_observed_months':int(len(training))}

@torch.no_grad()
def predict_rows(model,windows,normalizer,ser,crop,device):
    model.eval();rows=[]; mu=normalizer['mean'];sd=normalizer['sd']
    for start in range(0,len(windows),256):
        batch=windows[start:start+256]
        x=torch.from_numpy(np.stack([w['x'] for w in batch])).to(device)
        forecast=model(x).cpu().numpy()
        for k,w in enumerate(batch):
            origin=w['origin']
            for h in range(1,HORIZONS+1):
                if not w['mask'][h-1]:continue
                date=origin+pd.DateOffset(months=h)
                logp=np.clip(forecast[k,h-1]*sd+mu,-12,12)
                price=float(np.exp(logp))
                actual=float(ser.loc[date])
                history=ser.loc[:origin].dropna()
                seasonal=history[history.index.month==date.month]
                seasonal_price=float(seasonal.mean()) if len(seasonal) else w['last_price']
                rows.append({'crop_id':crop,'origin':origin.strftime('%Y-%m-%d'),
                    'target':date.strftime('%Y-%m-%d'),'horizon':h,
                    'actual_thb_kg':actual,'lstm_thb_kg':price,
                    'last_price_baseline_thb_kg':w['last_price'],
                    'seasonal_baseline_thb_kg':seasonal_price})
    return pd.DataFrame(rows)

def score_predictions(preds,split):
    rec=[]
    for horizon,g in preds.groupby('horizon'):
        actual=g.actual_thb_kg.to_numpy()
        result={'crop_id':g.crop_id.iloc[0],'split':split,'horizon':int(horizon),'samples':len(g),
                'mean_actual_price_thb_kg':float(np.mean(actual))}
        for name,col in [('lstm','lstm_thb_kg'),('last_price','last_price_baseline_thb_kg'),('seasonal','seasonal_baseline_thb_kg')]:
            err=g[col].to_numpy()-actual
            result[f'{name}_mae_thb_kg']=float(np.mean(np.abs(err)))
            result[f'{name}_rmse_thb_kg']=float(np.sqrt(np.mean(err**2)))
            result[f'{name}_wape_pct']=float(100*np.sum(np.abs(err))/max(np.sum(np.abs(actual)),1e-8))
        best_baseline=min(result['last_price_mae_thb_kg'],result['seasonal_mae_thb_kg'])
        result['best_baseline_mae_thb_kg']=best_baseline
        result['lstm_skill_vs_best_baseline_pct']=float(100*(best_baseline-result['lstm_mae_thb_kg'])/best_baseline) if best_baseline else np.nan
        rec.append(result)
    return pd.DataFrame(rec)

def draw_plots(test_preds,crop,out):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plotdir=out/'plots';plotdir.mkdir(exist_ok=True)
    for h,g in test_preds.groupby('horizon'):
        g=g.sort_values('target'); fig,ax=plt.subplots(figsize=(10,4))
        for col,name in [('actual_thb_kg','Actual'),('lstm_thb_kg','LSTM'),('last_price_baseline_thb_kg','Last known price')]:
            ax.plot(pd.to_datetime(g.target),g[col],label=name)
        ax.set(title=f'{crop}: {h}-month price forecast',ylabel='THB / kg',xlabel='Target month')
        ax.legend();fig.autofmt_xdate();fig.tight_layout()
        fig.savefig(plotdir/f'forecast_h{h}.png',dpi=125);plt.close(fig)

def train_one(crop,ser,args,root,device):
    set_seed(args.seed)
    out=root/safe_name(crop);out.mkdir(parents=True,exist_ok=True)
    windows,normalizer=make_windows(ser,args.lookback,pd.Timestamp(args.train_end),pd.Timestamp(args.val_end))
    counts={key:len(ws) for key,ws in windows.items()}
    if min(counts.values())<args.min_origins:
        print(f'  SKIPPING {crop}: too few origins {counts} (min={args.min_origins})',flush=True)
        return None
    model=IndividualLSTM(hidden=args.hidden,dropout=args.dropout).to(device)
    opt=torch.optim.AdamW(model.parameters(),lr=args.lr,weight_decay=args.weight_decay)
    train_loader=DataLoader(Windows(windows['train']),batch_size=args.batch_size,shuffle=True)
    val_loader=DataLoader(Windows(windows['val']),batch_size=128,shuffle=False)
    best=float('inf');stalled=0;hist=[];best_epoch=None
    for epoch in range(1,args.epochs+1):
        model.train(); train_num=0.;train_den=0.
        for x,y,m in train_loader:
            x=x.to(device);y=y.to(device);m=m.to(device)
            opt.zero_grad();p=model(x)
            loss=(torch.abs(p-y)*m).sum()/m.sum().clamp_min(1)
            loss.backward();nn.utils.clip_grad_norm_(model.parameters(),1.)
            opt.step();train_num+=float((torch.abs(p.detach()-y)*m).sum());train_den+=float(m.sum())
        model.eval();val_num=0.;val_den=0.
        with torch.no_grad():
            for x,y,m in val_loader:
                x=x.to(device);y=y.to(device);m=m.to(device)
                val_num+=float((torch.abs(model(x)-y)*m).sum());val_den+=float(m.sum())
        train_loss=train_num/max(train_den,1);val_loss=val_num/max(val_den,1)
        hist.append({'epoch':epoch,'train_masked_mae_log_z':train_loss,'val_masked_mae_log_z':val_loss})
        if val_loss<best-1e-5:
            best=val_loss;best_epoch=epoch;stalled=0;torch.save(model.state_dict(),out/'model.pt')
        else: stalled+=1
        if stalled>=args.patience:break
    pd.DataFrame(hist).to_csv(out/'training_history.csv',index=False)
    model.load_state_dict(torch.load(out/'model.pt',map_location=device,weights_only=True))
    cfg={'crop_id':crop,'normalization':normalizer,'lookback':args.lookback,
         'hidden_size':args.hidden,'dropout':args.dropout,'horizons':list(range(1,HORIZONS+1)),
         'train_end':args.train_end,'val_end':args.val_end,'best_epoch':best_epoch,
         'origin_counts':counts,'features':['log_price_z','observed','months_since_price_div24','sin_month','cos_month']}
    (out/'model_config.json').write_text(json.dumps(cfg,indent=2),encoding='utf-8')
    all_scores=[];preds_by_split={}
    for split in ('val','test'):
        p=predict_rows(model,windows[split],normalizer,ser,crop,device)
        if p.empty:continue
        p.to_csv(out/f'{split}_predictions.csv',index=False)
        s=score_predictions(p,split);s.to_csv(out/f'{split}_metrics.csv',index=False)
        all_scores.append(s);preds_by_split[split]=p
    if 'test' in preds_by_split and not args.no_plots:draw_plots(preds_by_split['test'],crop,out)
    if not all_scores:return None
    final=pd.concat(all_scores,ignore_index=True)
    v=final[final.split=='val'];t=final[final.split=='test']
    for split,data in [('val',v),('test',t)]:
        if len(data):
            print(f"  {split}: LSTM MAE {np.average(data.lstm_mae_thb_kg,weights=data.samples):.3f}  last-price MAE {np.average(data.last_price_mae_thb_kg,weights=data.samples):.3f}  seasonal MAE {np.average(data.seasonal_mae_thb_kg,weights=data.samples):.3f}",flush=True)
    return final

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--data',default='data/prices_long.csv');p.add_argument('--out',default='results_per_crop')
    p.add_argument('--crops',nargs='*',default=None,help='Optional crop IDs; default all')
    p.add_argument('--train-end',default='2020-12-01');p.add_argument('--val-end',default='2022-12-01')
    p.add_argument('--lookback',type=int,default=12);p.add_argument('--epochs',type=int,default=110)
    p.add_argument('--batch-size',type=int,default=32);p.add_argument('--hidden',type=int,default=16)
    p.add_argument('--dropout',type=float,default=0.25);p.add_argument('--lr',type=float,default=0.001)
    p.add_argument('--weight-decay',type=float,default=0.01);p.add_argument('--patience',type=int,default=15)
    p.add_argument('--min-origins',type=int,default=8);p.add_argument('--seed',type=int,default=42)
    p.add_argument('--no-plots',action='store_true');p.add_argument('--device',choices=['auto','cpu','cuda'],default='auto')
    args, _ = p.parse_known_args()
    if args.lookback<2 or args.hidden<2:raise ValueError('lookback and hidden must be >=2')
    if pd.Timestamp(args.train_end)>=pd.Timestamp(args.val_end):raise ValueError('Train must precede validation')
    device='cuda' if args.device=='auto' and torch.cuda.is_available() else ('cpu' if args.device=='auto' else args.device)
    root=Path(args.out);root.mkdir(parents=True,exist_ok=True)
    panel=get_panel(args.data)
    if args.crops:
        unknown=set(args.crops)-set(panel)
        if unknown:raise ValueError(f'Unknown crop IDs: {sorted(unknown)}')
        panel={c:panel[c] for c in args.crops}
    outputs=[]
    for ci,(crop,ser) in enumerate(panel.items(),1):
        print(f'[{ci}/{len(panel)}] Training independent LSTM for {crop}',flush=True)
        try:scores=train_one(crop,ser,args,root,device)
        except ValueError as exc:
            print('  SKIPPING',crop,':',exc,flush=True);continue
        if scores is not None:outputs.append(scores)
    if not outputs:raise RuntimeError('No crops trainable; check data coverage and dates')
    overall=pd.concat(outputs,ignore_index=True)
    overall.to_csv(root/'all_crop_metrics.csv',index=False)
    summary=[]
    for (crop,split),part in overall.groupby(['crop_id','split']):
        row={'crop_id':crop,'split':split,'observed_forecast_pairs':int(part.samples.sum()),'horizons_evaluated':int(len(part))}
        for metric in ['lstm','last_price','seasonal']:
            row[f'{metric}_mae_thb_kg']=float(np.average(part[f'{metric}_mae_thb_kg'],weights=part.samples))
            row[f'{metric}_wape_pct']=float(np.average(part[f'{metric}_wape_pct'],weights=part.samples))
        row['lstm_vs_last_price_pct']=100*(row['last_price_mae_thb_kg']-row['lstm_mae_thb_kg'])/row['last_price_mae_thb_kg']
        summary.append(row)
    pd.DataFrame(summary).sort_values(['crop_id','split']).to_csv(root/'crop_summary.csv',index=False)
    v=overall[overall.split=='val'].copy()
    v['selected_method']=v.apply(lambda r:min({'lstm':r.lstm_mae_thb_kg,'last_price':r.last_price_mae_thb_kg,'seasonal':r.seasonal_mae_thb_kg},key={'lstm':r.lstm_mae_thb_kg,'last_price':r.last_price_mae_thb_kg,'seasonal':r.seasonal_mae_thb_kg}.get),axis=1)
    choices=v[['crop_id','horizon','selected_method']]
    choices.to_csv(root/'validation_selected_methods.csv',index=False)
    t=overall[overall.split=='test'].merge(choices,on=['crop_id','horizon'],how='left')
    t['selected_test_mae_thb_kg']=t.apply(lambda r:r[f'{r.selected_method}_mae_thb_kg'] if isinstance(r.selected_method,str) else np.nan,axis=1)
    t.to_csv(root/'test_model_selection.csv',index=False)
    print('Saved independent crop models and all metrics under',root,flush=True)
    print('NOTE: test_model_selection.csv evaluates choices made strictly using validation.',flush=True)

if __name__=='__main__':main()