def load_daily(path, sites=None):
    df = pd.read_csv(path, low_memory=False)
    missing_cols = set(COLUMN_MAP) - set(df.columns)
    if missing_cols:
        raise ValueError(f'Daily input missing columns: {sorted(missing_cols)}')
    df = df.rename(columns=COLUMN_MAP)
    if sites: df = df[df.site.isin(sites)].copy()
    if df.empty: raise ValueError('No matching site data')
    df.date = pd.to_datetime(df.date, errors='raise')
    for c in [*DAILY_VARS, 'latitude','longitude']:
        df[c] = pd.to_numeric(df[c], errors='coerce')
    df[list(DAILY_VARS)] = df[list(DAILY_VARS)].replace(list(MISSING), np.nan)
    if df.duplicated(['site','date']).any(): raise ValueError('Duplicate site/date rows')
    df = df.sort_values(['site','date']).reset_index(drop=True)
    return df


def load_imerg(path, mode):
    if mode == 'none': return None
    df = pd.read_csv(path)
    need = {'month','thai_bbox_rainfall_mm'}
    if not need.issubset(df.columns): raise ValueError(f'IMERG missing: {need-set(df.columns)}')
    df['month'] = pd.to_datetime(df['month'].astype(str)).dt.to_period('M')
    df['thai_bbox_rainfall_mm'] = pd.to_numeric(df['thai_bbox_rainfall_mm'],errors='coerce')
    if df.duplicated('month').any(): raise ValueError('Duplicate IMERG month')
    return df.set_index('month')['thai_bbox_rainfall_mm'].sort_index()


def load_enso(path, mode):
    if mode == 'none':
        return None
    df = pd.read_csv(path)
    requested = ['oni','roni'] if mode == 'both' else [mode]
    required = {'center_month', *requested}
    if not required.issubset(df.columns):
        raise ValueError(f'ENSO input missing columns: {required-set(df.columns)}')
    df['center_month'] = pd.PeriodIndex(df['center_month'].astype(str), freq='M')
    if df.center_month.duplicated().any():
        raise ValueError('Duplicate ENSO center months')
    for col in requested:
        df[col] = pd.to_numeric(df[col], errors='coerce')
    return df.set_index('center_month')[requested].sort_index()


def add_enso_features(X, enso, delay):
    if enso is None:
        return X
    if delay < 2:
        raise ValueError('ENSO delay must be >= 2 months to avoid future months in centered 3-month seasons')
    out = X.copy()
    centers = out.origin_month - delay
    for index in enso.columns:
        ser = enso[index]
        for lag in (0,1,2,3):
            out[f'{index}_available_lag{lag}'] = (centers-lag).map(ser).to_numpy(dtype=float)
        # Only the already-available observations are used to create trends.
        out[f'{index}_change_3mo'] = out[f'{index}_available_lag0'] - out[f'{index}_available_lag3']
        out[f'{index}_recent3_avg'] = out[[f'{index}_available_lag{j}' for j in (0,1,2)]].mean(axis=1)
    out['enso_latest_center_month'] = centers.astype(str)
    return out


def aggregate_monthly(daily):
    d = daily.copy(); d['month'] = d.date.dt.to_period('M')
    g=d.groupby(['site','month'], sort=True, observed=True)
    monthly=g.agg(days=('date','nunique'), **{name:(name,'sum' if name=='rainfall_mm' else 'mean') for name in DAILY_VARS})
    monthly=monthly.reset_index()
    monthly['expected_days']=monthly['month'].dt.days_in_month
    monthly=monthly[monthly.days==monthly.expected_days].copy()
    counts=g[list(DAILY_VARS)].count().reset_index()
    monthly=monthly.merge(counts, on=['site','month'],suffixes=('','_valid'))
    for var in VARS:
        monthly.loc[monthly[f'{var}_valid']!=monthly['expected_days'],var] = np.nan
    monthly=monthly.drop(columns=[c for c in monthly if c.endswith('_valid')]+['expected_days'])
    return monthly


def cummean_interval(g, c, end_i, from_date):
    dates=g['date'].values
    start_i=int(np.searchsorted(dates, np.datetime64(from_date), side='left'))
    if start_i > end_i: return np.nan
    a=g[c].to_numpy(dtype=float)[start_i:end_i+1]
    return float(np.nanmean(a)) if np.isfinite(a).any() else np.nan


def features_and_labels(daily, monthly, imerg, delay, max_origin_year):
    monthly_index=monthly.set_index(['site','month'])
    feats=[]; lab=[]
    month_windows=[1,3,6,9]
    for site,g in daily.groupby('site', sort=True):
        g=g.sort_values('date').reset_index(drop=True)
        month_lookup=monthly[monthly.site==site].set_index('month')
        seen=g.set_index('date')
        for month in month_lookup.index:
            if month.year > max_origin_year: continue
            day=month.to_timestamp(how='end').normalize()
            if day not in seen.index: continue
            if day - g.date.iloc[0] < pd.Timedelta(days=280): continue
            i=int(g.date.searchsorted(day))
            if i>=len(g) or g.date.iloc[i] != day: continue
            row=seen.loc[day]
            f={'site':site, 'origin_month':month,'origin_date':day,
               'latitude':float(row.latitude),'longitude':float(row.longitude),
               'broad_region':str(row.broad_region),
               'year':int(month.year),'month_num':int(month.month),
               'month_sin':float(np.sin(2*np.pi*month.month/12)),
               'month_cos':float(np.cos(2*np.pi*month.month/12))}
            for v in DAILY_VARS:
                f[f'current_{v}']=row[v]
                for n in (3,7,14):
                    f[f'{v}_rolling_{n}d'] = cummean_interval(g,v,i,day-pd.Timedelta(days=n-1))
                for m in month_windows:
                    start=day-pd.DateOffset(months=m)+pd.Timedelta(days=1)
                    f[f'{v}_rolling_{m}mo']=cummean_interval(g,v,i,start)
            if imerg is not None:
                for j in range(3):
                    available=month-(delay+j)
                    f[f'imerg_regional_lag_available_{j+1}']=imerg.get(available, np.nan)
            for h in HORIZONS:
                target=month+h
                f[f'target_month_h{h}']=str(target)
                for v in VARS:
                    lab.append({'site':site,'origin_month':str(month),
                                'horizon':h,'target_month':str(target),'variable':v,
                                'actual':float(month_lookup.loc[target,v]) if target in month_lookup.index else np.nan})
            feats.append(f)
    X=pd.DataFrame(feats)
    if X.empty: raise RuntimeError('No valid monthly forecast origins')
    return X,pd.DataFrame(lab)


def add_climatology_features(X, monthly):
    out = X.copy()
    variables = list(VARS)
    for h in HORIZONS:
        for v in variables:
            out[f'climatology_{v}_h{h}'] = np.nan

    for site, idx in out.groupby('site', sort=True).groups.items():
        site_monthly = monthly[monthly.site == site].sort_values('month').copy()
        histories = {}
        for calmonth, group in site_monthly.groupby(site_monthly.month.dt.month):
            histories[int(calmonth)] = {}
            periods = group.month.astype('int64').to_numpy()
            for v in variables:
                values = pd.to_numeric(group[v], errors='coerce').to_numpy(dtype=float)
                valid = np.isfinite(values)
                histories[int(calmonth)][v] = (
                    periods, np.cumsum(np.where(valid, values, 0.0)), np.cumsum(valid)
                )

        for row_idx in idx:
            origin = out.at[row_idx,'origin_month']
            origin_id = origin.ordinal
            for h in HORIZONS:
                target_calmonth = (origin + h).month
                for v in variables:
                    period_ids, cum_sum, cum_n = histories[target_calmonth][v]
                    last = np.searchsorted(period_ids, origin_id, side='right') - 1
                    if last >= 0 and cum_n[last] > 0:
                        out.at[row_idx, f'climatology_{v}_h{h}'] = cum_sum[last] / cum_n[last]
    return out


def graph_predictions(predictions, output):
    for (v,h),g in predictions.groupby(['variable','horizon']):
        agg=g.groupby('target_month')[['actual','predicted','seasonal_baseline']].mean().sort_index()
        if agg.empty:continue
        fig,ax=plt.subplots(figsize=(12,4))
        xx=pd.PeriodIndex(agg.index,freq='M').to_timestamp()
        ax.plot(xx,agg.actual.values,label='Actual (mean across sites)',linewidth=1.7)
        ax.plot(xx,agg.predicted.values,label='XGBoost + climatology features',linewidth=1.3)
        ax.plot(xx,agg.seasonal_baseline.values,label='Seasonal baseline',alpha=.7)
        ax.set(title=f'{v} — {h}-month-ahead forecast',xlabel='Target month',ylabel=v)
        ax.legend();fig.autofmt_xdate();fig.tight_layout()
        fig.savefig(output / f'forecast_{v}_h{h}.png',dpi=140)
        plt.close(fig)


def main():
    args=parse_args()
    if args.n_estimators<=0 or args.max_depth<1 or args.threads<1: raise ValueError('Invalid XGBoost hyperparameters')
    out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    test_start=pd.Period(args.test_start,freq='M')
    daily=load_daily(args.power,args.sites)
    monthly=aggregate_monthly(daily)
    imerg=load_imerg(args.imerg,args.imerg_mode)
    enso=load_enso(args.enso,args.enso_mode)
    X,labels=features_and_labels(daily,monthly,imerg,args.imerg_delay,args.max_origin_year)
    X=add_enso_features(X,enso,args.enso_delay_months)
    X=add_climatology_features(X,monthly)
    clim_cols=[f'climatology_{v}_h{h}' for h in HORIZONS for v in VARS]
    X['origin_month']=X.origin_month.astype(str)
    core=[c for c in X if c.startswith('current_') or '_rolling_' in c or
          c.startswith('imerg_') or c.startswith('oni_') or c.startswith('roni_')]
    feature_cols=['latitude','longitude','year','month_num','month_sin','month_cos',*core]
    if args.climatology_features=='all':
        feature_cols += clim_cols
    regions=pd.get_dummies(X['broad_region'],prefix='region',dtype=np.uint8)
    X=pd.concat([X,regions],axis=1)
    feature_cols+=regions.columns.tolist()
    X[feature_cols]=X[feature_cols].apply(pd.to_numeric,errors='coerce')
    X.to_csv(out/'features_with_climatology.csv',index=False)
    merge_cols=list(dict.fromkeys(['site','origin_month',*feature_cols,*clim_cols]))
    labels=labels.merge(X[merge_cols],on=['site','origin_month'],how='inner',validate='many_to_one')
    labels['origin_period']=pd.PeriodIndex(labels.origin_month,freq='M')
    labels['target_period']=pd.PeriodIndex(labels.target_month,freq='M')
    res=[];preds=[];aud=[]
    cfg={'test_start':str(test_start),'source_rows':len(daily),'monthly_rows':len(monthly),
         'origins':len(X),'sites':sorted(daily.site.unique().tolist()),
         'imerg_mode':args.imerg_mode,'imerg_delay':args.imerg_delay,
         'enso_mode':args.enso_mode,'enso_delay_months':args.enso_delay_months,
         'NOAA_caveat':'Revised NOAA values with a conservative 3-month centered-index lag; not historical as-issued vintages',
         'climatology_features':args.climatology_features,
         'climatology_rule':'same target calendar month, same site, historical months <= origin only',
         'n_estimators':args.n_estimators,'max_depth':args.max_depth,'learning_rate':args.learning_rate,'threads':args.threads,'features':feature_cols,
         'forecast_origin':'last day of each complete month','horizons':list(HORIZONS)}
    (out/'config.json').write_text(json.dumps(cfg,indent=2))
    print(f'Loaded {len(daily):,} daily rows, {len(monthly):,} monthly rows, {len(X):,} forecast origins; {len(feature_cols)} XGBoost features, climatology={args.climatology_features} (no SARIMAX).',flush=True)
    for v in args.targets:
        for h in HORIZONS:
            t=labels[(labels.variable==v)&(labels.horizon==h)&labels.actual.notna()].copy()
            train=t[(t.origin_period<test_start)&(t.target_period<test_start)].copy()
            test=t[t.origin_period>=test_start].copy()
            if len(train)<50 or len(test)<5:
                print(f'SKIP {v} horizon {h}: train={len(train)}, test={len(test)}',flush=True)
                continue
            usable=[c for c in feature_cols if train[c].notna().any()]
            if not usable: raise RuntimeError('No valid input features')
            model=XGBRegressor(n_estimators=args.n_estimators,max_depth=args.max_depth,
                               learning_rate=args.learning_rate,subsample=.85,
                               colsample_bytree=.85,reg_lambda=8,
                               objective='reg:squarederror',tree_method='hist',
                               n_jobs=args.threads,random_state=42)
            model.fit(train[usable],train.actual.to_numpy())
            yhat=model.predict(test[usable])
            if v=='rainfall_mm': yhat=np.maximum(yhat,0.)
            y=test.actual.to_numpy(dtype=float)
            base=test[f'climatology_{v}_h{h}'].to_numpy(dtype=float)
            valid=np.isfinite(base)
            mae=float(mean_absolute_error(y,yhat));rmse=float(np.sqrt(mean_squared_error(y,yhat)))
            bm=float(mean_absolute_error(y[valid],base[valid])) if valid.any() else np.nan
            br=float(np.sqrt(mean_squared_error(y[valid],base[valid]))) if valid.any() else np.nan
            res.append({'variable':v,'horizon_months':h,'train_rows':len(train),'test_rows':len(test),
                        'mae':mae,'rmse':rmse,'baseline_mae':bm,'baseline_rmse':br,
                        'mae_skill_vs_climatology':1-mae/bm if bm>0 else np.nan})
            aud.append({'variable':v,'horizon_months':h,'last_train_target':str(train.target_period.max()),
                        'first_test_origin':str(test.origin_period.min()),
                        'last_test_origin':str(test.origin_period.max()),'n_features':len(usable)})
            for s,o,targ,a,p,b in zip(test.site,test.origin_month,test.target_month,y,yhat,base):
                preds.append({'site':s,'origin_month':o,'target_month':targ,
                              'variable':v,'horizon':h,'actual':a,
                              'predicted':float(p),'seasonal_baseline':float(b)})
            if not args.no_model_save:
                (out/'models').mkdir(exist_ok=True)
                dump({'model':model,'feature_cols':usable,'variable':v,'horizon':h,'test_start':str(test_start)},
                     out/'models'/f'xgboost_{v}_h{h}.joblib')
            print(f'{v} horizon {h}: MAE {mae:.3f}, RMSE {rmse:.3f}, baseline MAE {bm:.3f}',flush=True)
    pd.DataFrame(res).to_csv(out/'metrics.csv',index=False)
    pd.DataFrame(aud).to_csv(out/'leakage_audit.csv',index=False)
    if preds:
        pred=pd.DataFrame(preds)
        pred.to_csv(out/'predictions.csv',index=False)
        ss=[]
        for (v,h,site),g in pred.groupby(['variable','horizon','site']):
            ss.append({'variable':v,'horizon_months':h,'site':site,'n':len(g),
                       'mae':float(mean_absolute_error(g.actual,g.predicted)),
                       'rmse':float(np.sqrt(mean_squared_error(g.actual,g.predicted)))})
        pd.DataFrame(ss).to_csv(out/'site_metrics.csv',index=False)
        if not args.no_plots:
            graph_predictions(pred,out)
    print('Complete:',out.resolve(),flush=True)

if __name__=='__main__': main()