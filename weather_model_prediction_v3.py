from xgboost import XGBRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error

HORIZONS = (1, 2, 3, 6, 9)
VARS = {
    'rainfall_mm': 'Rainfall (mm/day)',
    'temperature_c': 'Temperature (C)',
    'wind_ms': 'Wind (m/s)',
    'solar_mj_m2_day': 'Solar (MJ/m2/day)',
    'humidity_pct': 'Humidity (%)',
}
EXTRA = {'rootzone_wetness': 'Root-zone wetness'}
DAILY_VARS = {**VARS, **EXTRA}
COLUMN_MAP = {'Site':'site','Date':'date','Region (source)':'region_source',
              'Broad region':'broad_region','Latitude':'latitude','Longitude':'longitude',
              **{v:k for k,v in DAILY_VARS.items()}}
MISSING = (-999, -999.0, -99, -99.0, -9999.0)


