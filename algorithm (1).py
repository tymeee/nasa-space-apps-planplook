WEATHER_MODE = "xgboost"
MONTHLY_WEATHER = Path("/content/monthly_weather_forecasts.csv")
MODEL_DIR = Path("/content/xgboost_weather_inputs")
WEATHER_FEATURES = MODEL_DIR / "features_with_climatology.csv"
WEATHER_FEATURE_INPUT = "raw"
WEATHER_POWER = MODEL_DIR / "power_daily_16_sites.csv"
WEATHER_ENSO = MODEL_DIR / "noaa_oni_roni_1950_2026.csv"
WEATHER_IMERG = RAIN_HISTORY
WEATHER_FEATURE_SITE = None
WEATHER_IMERG_DELAY = 4
WEATHER_ENSO_DELAY = 3

PADDY_ALLOWED = False
UPLAND_ALLOWED = True
ALLOW_SEASONAL_RICE = False
IRRIGATION_MM_DAY = 0.0
PADDY_LOSS_MM_DAY = None
USE_DEFAULT_SOIL_BANDS = True

SOIL_HYDRAULICS = {"surface": (.32, .15), "rootzone": (.32, .15)}
SOIL_BAND_OVERRIDES = {}
if WEATHER_FEATURE_INPUT not in ("raw", "exported_csv"):
    raise ValueError("Set WEATHER_FEATURE_INPUT to raw or exported_csv.")
weather_inputs = (
    [WEATHER_POWER, WEATHER_ENSO, WEATHER_IMERG]
    if WEATHER_FEATURE_INPUT == "raw" else [WEATHER_FEATURES]
)
if WEATHER_MODE != "xgboost" or prepare_xgboost_uploads(weather_inputs, MODEL_DIR):
    OUTPUT.mkdir(parents=True, exist_ok=True)
    start = soil_forecast_start(SOIL_FORECAST, FIELD_ID)
    SOIL_BANDS = (
        build_demo_soil_bands(locate(SMAP_HISTORY), FIELD_ID, start, SOIL_HYDRAULICS)
        if USE_DEFAULT_SOIL_BANDS else {}
    )
    for crop, overrides in SOIL_BAND_OVERRIDES.items():
        SOIL_BANDS.setdefault(crop, {}).update(overrides)
    soil_ranges = pd.DataFrame([
        {"field_id": FIELD_ID, "crop": crop, "variable": variable, "minimum": low,
         "maximum": high,
         "basis": ("user_override" if variable in SOIL_BAND_OVERRIDES.get(crop, {})
                   else "illustrative_paddy_saturation" if any(c.name == crop and c.paddy for c in CROPS)
                   else "fao_example_silt_with_smap_porosity")}
        for crop, limits in SOIL_BANDS.items() for variable, (low, high) in limits.items()
    ], columns=["field_id", "crop", "variable", "minimum", "maximum", "basis"])
    soil_ranges.to_csv(OUTPUT / "soil_bands_used.csv", index=False)
    display(soil_ranges.round(4))
    if WEATHER_MODE == "power_baseline":
        weather = power_normals(locate(POWER_HISTORY), FIELD_ID, start, WEATHER)
        solar_source = "power_calendar_month_normal"
    elif WEATHER_MODE == "monthly_csv":
        weather = validate_weather(locate(MONTHLY_WEATHER), FIELD_ID, start)
        solar_source = "supplied_monthly_weather"
    elif WEATHER_MODE == "xgboost":
        baseline = power_normals(locate(POWER_HISTORY), FIELD_ID, start, WEATHER)
        feature_path = WEATHER_FEATURES
        if WEATHER_FEATURE_INPUT == "raw":
            feature_row = build_original_weather_features(
                locate(WEATHER_POWER), locate(WEATHER_IMERG), locate(WEATHER_ENSO),
                FIELD_ID, start, WEATHER_FEATURE_SITE, WEATHER_IMERG_DELAY, WEATHER_ENSO_DELAY,
            )
            feature_path = OUTPUT / "generated_weather_features.csv"
            feature_row.to_csv(feature_path, index=False)
        weather = model_weather(locate(feature_path), MODEL_DIR, FIELD_ID, start,
                                baseline, WEATHER_FEATURE_SITE)
        solar_source = "power_calendar_month_normal"
    else:
        raise ValueError("Choose weather mode: power_baseline, monthly_csv, or xgboost.")

    weather_path = OUTPUT / "monthly_weather_forecasts.csv"
    weather.rename_axis("month").assign(field_id=FIELD_ID).reset_index().to_csv(weather_path,index=False)
    conditions = read_conditions(soil_path=SOIL_FORECAST, weather_path=weather_path, field_id=FIELD_ID)
    combined = conditions.rename_axis("month").assign(
        field_id=FIELD_ID, weather_source=WEATHER_MODE, solar_source=solar_source,
        soil_resolution="three_month_blocks", soil_forecast_file=SOIL_FORECAST.name,
    ).reset_index()
    source_columns = [name for name in weather if name.endswith("_source") and name != "solar_source"]
    if source_columns:
        combined = combined.merge(weather[source_columns].rename_axis("month").reset_index(),
                                  on="month", validate="one_to_one")
    combined.to_csv(OUTPUT / "combined_crop_conditions.csv", index=False)

    eligible_crops = [c for c in CROPS if (PADDY_ALLOWED if c.paddy else UPLAND_ALLOWED)
                      and (ALLOW_SEASONAL_RICE or not c.seasonal)]
    missing_bands = {c.name: sorted(set(SOIL_COLUMNS)-set(SOIL_BANDS.get(c.name, {})))
                     for c in eligible_crops if set(SOIL_COLUMNS)-set(SOIL_BANDS.get(c.name, {}))}
    if missing_bands:
        print("Soil predictions are in the combined file. Ranking uses only the soil bands you supply.")
        print("Missing bands for eligible crops:", missing_bands)

    summaries, stages = zip(*(rank_plans(
        conditions, h, paddy_allowed=PADDY_ALLOWED, upland_allowed=UPLAND_ALLOWED,
        allow_seasonal_rice=ALLOW_SEASONAL_RICE, irrigation_mm_day=IRRIGATION_MM_DAY,
        paddy_loss_mm_day=PADDY_LOSS_MM_DAY, soil_bands=SOIL_BANDS,
    ) for h in (3,6,9)))
    plans = pd.concat(summaries,ignore_index=True).assign(
        field_id=FIELD_ID, weather_source=WEATHER_MODE,
        all_eligible_crops_have_four_soil_bands=not missing_bands)
    details = pd.concat(stages,ignore_index=True).assign(field_id=FIELD_ID)
    plans.to_csv(OUTPUT / "ranked_plans.csv",index=False)
    details.to_csv(OUTPUT / "planting_and_harvest_dates.csv",index=False)
    display(plans)
    score_columns = ["horizon_months", "rank", "step", "crop", "fit",
                     "temperature_fit", "rainfall_only_score", "humidity_demand_score",
                     "solar_demand_score", "water_fit", "soil_fit", "soil_weight",
                     *[f"{label}_score" for label in SOIL]]
    display(details.reindex(columns=score_columns))
    print(f"Outputs saved to {OUTPUT}")