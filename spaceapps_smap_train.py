TARGETS = ["surface_moisture_m3_m3", "rootzone_moisture_m3_m3",
           "surface_wetness_fraction", "rootzone_wetness_fraction"]
HORIZONS = (3, 6, 9)
SEED = 42
RAIN_LAG = 4

def read_inputs(smap_path, rain_path):
    smap = pd.read_csv(smap_path, parse_dates=["date"], dtype={"field_id": str})
    if smap.empty or smap[["field_id", "date"]].isna().any().any():
        raise ValueError("SMAP needs a field_id and date on every row.")
    if smap.duplicated(["field_id", "date"]).any() or not smap.date.dt.day.eq(1).all():
        raise ValueError("Use the monthly SMAP export with one row per site and month.")
    if not smap[TARGETS].stack().between(0, 1).all():
        raise ValueError("SMAP moisture and wetness values must be in [0, 1].")
    dates = pd.date_range("2015-01-01", "2025-12-01", freq="MS")
    rain = pd.read_csv(rain_path, usecols=["month", "thai_bbox_rainfall_mm"])
    rain["month"] = parse_month(rain.month)
    dates = pd.date_range(dates.min(), max(dates.max(), smap.date.max()), freq="MS")
    rain = rain.loc[rain.month.between(dates.min(), dates.max())]
    observed = rain.thai_bbox_rainfall_mm.dropna()
    if rain.month.duplicated().any() or observed.empty or not observed.between(0, np.inf, inclusive="left").all():
        raise ValueError("Rainfall needs unique months and valid, nonnegative totals.")
    rain = rain.set_index("month").thai_bbox_rainfall_mm.reindex(dates)
    print(f"Rainfall: {rain.count()} months, {rain.first_valid_index():%Y-%m} to {rain.last_valid_index():%Y-%m}.")
    rain_features = pd.DataFrame({
        "rain_last_available_mm": rain.shift(RAIN_LAG),
        "rain_3month_total_mm": rain.rolling(3, min_periods=3).sum().shift(RAIN_LAG),
        "rain_6month_total_mm": rain.rolling(6, min_periods=6).sum().shift(RAIN_LAG),
    })
    smap = smap.loc[smap.date.ge(dates.min())]
    if smap.empty:
        raise ValueError("No SMAP rows found during 2015–2025.")
    dates = pd.date_range(smap.date.min(), smap.date.max(), freq="MS")
    grid = pd.MultiIndex.from_product([sorted(smap.field_id.unique()), dates],
                                      names=["field_id", "date"])
    columns = ["field_id", "date"]
    data = (smap.set_index(columns).reindex(grid).reset_index()
            .join(rain_features, on="date", validate="many_to_one"))
    return data, list(rain_features.columns)

def build_windows(data, target, horizon):
    sites = data.groupby("field_id", sort=False)[target]
    frame = data[["field_id", "date", "latitude", "longitude"]].copy()
    frame["current"] = data[target]
    frame["last_3_month_mean"] = sites.transform(lambda s: s.rolling(3).mean())
    frame["last_6_month_mean"] = sites.transform(lambda s: s.rolling(6).mean())
    frame["current_vs_last_year"] = data[target] - sites.shift(12)
    usual = data.groupby(["field_id", data.date.dt.month])[target].transform(
        lambda s: s.shift(1).expanding().mean()
    )
    frame["current_vs_usual"] = data[target] - usual
    frame["forecast_start"] = frame.date + pd.offsets.MonthBegin(1)
    frame["forecast_end"] = frame.date + pd.offsets.MonthBegin(horizon)
    angle = 2 * np.pi * (frame.forecast_start.dt.month - 1) / 12
    frame["month_sin"], frame["month_cos"] = np.sin(angle), np.cos(angle)
    frame["actual"] = sites.transform(lambda s: s.rolling(horizon).mean().shift(-horizon))
    frame["last_year"] = sites.transform(lambda s: s.rolling(horizon).mean().shift(12-horizon))
    for step in range(1, horizon + 1):
        shift = 12 - step
        frame[f"normal_{step}"] = usual.groupby(data.field_id, sort=False).shift(shift)
        past = sites.shift(shift)
        count = data[target].notna().groupby([data.field_id, data.date.dt.month]).transform(
            lambda x: x.shift(1, fill_value=False).cumsum()
        ).groupby(data.field_id, sort=False).shift(shift)
        prior = frame[f"normal_{step}"]
        frame[f"normal_{step}"] = (
            (prior.fillna(0) * count + past.fillna(0)) / (count + past.notna())
        ).where(count + past.notna() > 0)
    frame["normal"] = frame[[f"normal_{i}" for i in range(1, horizon + 1)]].mean(axis=1, skipna=False)
    return frame

def make_estimator(family):
    imputer = SimpleImputer(strategy="median", add_indicator=True, keep_empty_features=True)
    if family == "ridge":
        return make_pipeline(imputer, StandardScaler(), Ridge(alpha=10))
    return make_pipeline(imputer, ExtraTreesRegressor(
        n_estimators=150, min_samples_leaf=8, n_jobs=2, random_state=SEED))


def parse_month(values):
    dates = pd.to_datetime(values, format="mixed", errors="raise")
    if dates.isna().any() or not dates.dt.day.eq(1).all():
        raise ValueError("Use YYYY-MM or YYYY-MM-01 for monthly dates.")
    return dates

def read_local(path, data, delay):
    rain = pd.read_csv(path, dtype={"field_id": str})
    rain["month"] = parse_month(rain.month)
    rain["rainfall_mm"] = pd.to_numeric(rain.rainfall_mm)
    values = rain.rainfall_mm.dropna()
    if values.empty or not np.isfinite(values).all() or values.lt(0).any():
        raise ValueError("Local rainfall must be nonnegative monthly totals in mm.")
    rain = rain.loc[rain.field_id.isin(data.field_id)].copy()
    if rain.empty or rain.duplicated(["field_id", "month"]).any():
        raise ValueError("Local rainfall needs matching SMAP field IDs and unique site/month rows.")
    dates = pd.date_range(min(rain.month.min(), data.date.min()),
                          data.date.max(), freq="MS")
    grid = pd.MultiIndex.from_product([data.field_id.unique(), dates], names=["field_id","month"])
    rain = rain.set_index(["field_id","month"]).reindex(grid).reset_index()
    groups = rain.groupby("field_id", sort=False).rainfall_mm
    columns = []
    for n in (1, 3, 6):
        total = groups.transform(lambda s: s.rolling(n).sum())
        normal = total.groupby([rain.field_id, rain.month.dt.month]).transform(
            lambda s: s.shift(1).expanding().mean())
        for label, value in ((f"local_rain_{n}m_mm", total), (f"local_rain_{n}m_anomaly_mm", total-normal)):
            rain[label] = value.groupby(rain.field_id).shift(delay)
            columns.append(label)
    return rain, columns

def read_archive(path, data):
    table = pd.read_csv(path, dtype={"field_id": str})
    table["valid_month"] = parse_month(table.valid_month)
    table["issued_at"] = pd.to_datetime(table.issued_at, utc=True).dt.tz_convert(None)
    table["forecast_rain_mm"] = pd.to_numeric(table.forecast_rain_mm)
    table = table.loc[table.field_id.isin(data.field_id)]
    if (table.empty or table[["issued_at","forecast_rain_mm"]].isna().any().any()
        or not np.isfinite(table.forecast_rain_mm).all() or table.forecast_rain_mm.lt(0).any()
        or table.duplicated(["field_id","valid_month","issued_at"]).any()):
        raise ValueError("Supply unique site/valid-month/issue rows with matching IDs, valid issues and monthly totals.")
    return {(site, month): group.sort_values("issued_at").set_index("issued_at").forecast_rain_mm
            for (site, month), group in table.groupby(["field_id","valid_month"])}

def add_archive_features(frame, archive, local, horizon, delay):
    observations = {} if local is None else {
        site: group.set_index("month").rainfall_mm for site, group in local.groupby("field_id")
    }
    rows = []
    for row in frame.itertuples():
        cutoff = row.forecast_start
        available = row.date - pd.DateOffset(months=delay)
        history = observations.get(row.field_id, pd.Series(dtype=float, index=pd.DatetimeIndex([])))
        known = history.loc[:available]
        normals = known.groupby(known.index.month).mean()
        predicted, covered, filled, normal_values = [], 0, [], []
        for month in pd.date_range(row.forecast_start, row.forecast_end, freq="MS"):
            issued = archive.get((row.field_id, month))
            known_forecasts = issued.loc[issued.index < cutoff] if issued is not None else ()
            normal = normals.get(month.month, np.nan)
            if len(known_forecasts):
                value = known_forecasts.iloc[-1]
                covered += 1
                predicted.append(value)
            else:
                value = normal
            filled.append(value)
            normal_values.append(normal)
        rows.append((covered/horizon, np.mean(predicted) if predicted else np.nan,
                     np.sum(filled) - np.sum(normal_values) if covered else np.nan))
    names = ["archive_fraction", "archive_covered_mean_mm", "archive_window_anomaly_mm"]
    return frame.join(pd.DataFrame(rows, index=frame.index, columns=names)), names

def comparison(data, rain_columns, local=None, local_cols=(), archive=None, local_delay=1):
    results, predictions, forecasts = [], [], []
    coords = data.groupby("field_id")[["latitude","longitude"]].transform("first")
    data = data.assign(latitude=coords.latitude, longitude=coords.longitude)
    core = ["latitude","longitude","current","last_3_month_mean","last_6_month_mean",
            "current_vs_last_year","current_vs_usual","month_sin","month_cos","last_year","normal"]
    feature_sets = {"smap_only": [], "regional_rain": rain_columns}
    if local is not None:
        data = data.merge(local[["field_id","month",*local_cols]].rename(columns={"month":"date"}),
                          on=["field_id","date"], how="left", validate="one_to_one")
        feature_sets["local_rain"] = list(local_cols)

    for target, horizon in product(TARGETS, HORIZONS):
        frame = build_windows(data, target, horizon).join(data[rain_columns+list(local_cols)])
        sets = feature_sets.copy()
        if archive:
            frame, archive_cols = add_archive_features(frame, archive, local, horizon, local_delay)
            label = "local_rain" if local is not None else "regional_rain"
            sets[label+"_plus_archive"] = sets[label] + archive_cols
        rows = frame.dropna(subset=["current","actual","last_year","normal"])
        months = pd.Index(sorted(data.loc[data[target].notna(),"date"].unique()))
        if len(months) < 60:
            raise ValueError(f"Too few months for {target} rolling validation.")
        cuts = [months[int(f*len(months))] for f in (.38,.52,.66,.8)]
        folds = [(rows.loc[rows.forecast_end < a],
                  rows.loc[(rows.forecast_start >= a) & (rows.forecast_end < b)])
                 for a,b in zip(cuts,cuts[1:])]
        folds = [(train,val) for train,val in folds if len(train) and len(val)]
        test = rows.loc[rows.forecast_start >= cuts[-1]]
        dev = rows.loc[rows.forecast_end < cuts[-1]]
        if len(folds) < 2 or test.empty:
            raise ValueError(f"Insufficient complete windows for {target}, {horizon} months.")
        future = (frame.dropna(subset=["current","last_year","normal"])
                  .groupby("field_id",sort=False).tail(1))

        def baseline(part, weight):
            return weight*part.last_year + (1-weight)*part.normal

        candidates = []
        for weight in (1., .75, .5, .25, 0.):
            errors = [abs(val.actual-baseline(val,weight)) for _,val in folds]
            candidates.append(("seasonal_only", weight, 0., np.concatenate(errors).mean(), []))
        for weight, family, (source, extra) in product(
                (1., .75, .5, .25, 0.), ("ridge","extra_trees"), sets.items()):
            columns = core+extra
            if extra and not all(train[extra].notna().any().any() for train,_ in folds):
                continue
            if source.endswith("_plus_archive") and not all(
                train.archive_fraction.gt(0).any() for train,_ in folds
            ):
                continue
            errors = {strength: [] for strength in (.25,.5,.75,1.)}
            for train,val in folds:
                estimator = make_estimator(family).fit(train[columns], train.actual-baseline(train,weight))
                correction = estimator.predict(val[columns])
                for strength in errors:
                    errors[strength].extend(abs(val.actual-np.clip(
                        baseline(val,weight)+strength*correction,0,1)))
            for strength, values in errors.items():
                candidates.append((f"{family}_{source}",weight,strength,np.mean(values),columns))
        winner = min(range(len(candidates)), key=lambda i: candidates[i][3])
        actual = test.actual.to_numpy()
        denom = np.sum((actual-actual.mean())**2)
        cache = {}
        for i,(name,weight,strength,val_mae,columns) in enumerate(candidates):
            predicted = baseline(test,weight).to_numpy()
            if strength:
                family = "ridge" if name.startswith("ridge_") else "extra_trees"
                cache_key = (name,weight)
                if cache_key not in cache:
                    estimator = make_estimator(family).fit(dev[columns],dev.actual-baseline(dev,weight))
                    cache[cache_key] = estimator.predict(test[columns])
                predicted = np.clip(predicted+strength*cache[cache_key],0,1)
            error = predicted-actual
            tag = dict(target=target,horizon_months=horizon,model=name,
                       last_year_weight=weight,correction_weight=strength,selected_on_validation=i==winner)
            results.append(dict(**tag,validation_mae=val_mae,test_mae=np.abs(error).mean(),
                                test_rmse=np.sqrt(np.mean(error**2)),
                                test_r2=1-np.sum(error**2)/denom if denom else np.nan,
                                test_n=len(test),test_start=cuts[-1],
                                test_local_rain_rows=int(test[local_cols[0]].notna().sum()) if local_cols else 0,
                                test_archive_rows=int(test.archive_fraction.gt(0).sum()) if archive else 0))
            if i in (0,winner):
                predictions.append(test[["field_id","date","forecast_start","forecast_end","actual"]]
                                   .assign(**tag,prediction=predicted))
            if i == winner and len(future):
                values = baseline(future,weight).to_numpy()
                if strength:
                    estimator = make_estimator(family).fit(rows[columns],rows.actual-baseline(rows,weight))
                    values = np.clip(values+strength*estimator.predict(future[columns]),0,1)
                forecasts.append(future[["field_id","date","forecast_start","forecast_end","latitude","longitude"]]
                                 .assign(**tag,prediction=values))
        print(f"{target}, {horizon} months: {candidates[winner][:3]}", flush=True)
    return pd.DataFrame(results), pd.concat(predictions), pd.concat(forecasts)

