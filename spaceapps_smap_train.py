def lookup(row, offset):
    month = row.date + pd.DateOffset(months=offset)
    return history[row.target].get((row.field_id, month), np.nan)

def window_mean(row, offset):
    values = [lookup(row, k + offset) for k in range(1, int(row.horizon_months) + 1)]
    return np.mean(values) if np.isfinite(values).all() else np.nan

rows["observed_check"] = rows.apply(window_mean, axis=1, offset=0)
if not np.allclose(rows.actual, rows.observed_check, atol=1e-8, rtol=1e-7):
    raise ValueError("The monthly CSV does not reproduce the model's observed test averages. Use the original input file.")
rows["persistence"] = rows.apply(lookup, axis=1, offset=0)
rows["same_window_last_year"] = rows.apply(window_mean, axis=1, offset=-12)

def historical_seasonal_average(row):
    series = history[row.target].xs(row.field_id).loc[:row.date]
    by_month = series.groupby(series.index.month).mean()
    window = pd.date_range(row.forecast_start, row.forecast_end, freq="MS")
    values = by_month.reindex(window.month).to_numpy()
    return np.mean(values) if np.isfinite(values).all() else np.nan

rows["historical_seasonal_average"] = rows.apply(historical_seasonal_average, axis=1)

def score(groups, comparisons):
    results = []
    for (target, horizon), frame in groups.groupby(["target", "horizon_months"]):
        common = frame.dropna(subset=["actual", *comparisons])
        if common.empty:
            continue
        actual = common.actual.to_numpy()
        total = ((actual - actual.mean())**2).sum()
        for name in comparisons:
            error = common[name].to_numpy() - actual
            results.append({
                "target": target, "horizon_months": horizon, "source": name,
                "mae": np.abs(error).mean(), "rmse": np.sqrt((error**2).mean()),
                "r2": 1 - (error**2).sum() / total if total > 0 else np.nan,
                "n": len(common), "available_model_rows": len(frame),
            })
    return pd.DataFrame(results)

